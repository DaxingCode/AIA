    private let table: [String: FoodRef]

    init() {
        var map: [String: FoodRef] = [:]
        for (name, kcal, p, c, f) in rows {
            map[name] = FoodRef(name: name, kcal: kcal, protein: p, carbs: c, fat: f)
        }
        table = map
    }

    /// 按食物名称匹配营养库。精确 > 包含（取最长命中键）。
    func match(_ name: String) -> FoodRef? {
        let key = normalize(name)
        guard !key.isEmpty else { return nil }
        // 1) 精确匹配
        if let exact = table[key] { return exact }
        // 2) 子串匹配：取长度最长的命中键（更具体优先）
        let hits = table.keys.filter { key.contains($0) || $0.contains(key) }
            .sorted { $0.count > $1.count }
        if let best = hits.first, let ref = table[best] {
            return ref
        }
        return nil
    }

    private func normalize(_ s: String) -> String {
        s.trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased()
            .replacingOccurrences(of: " ", with: "")
    }
